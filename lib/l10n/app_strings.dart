class AppStrings {
  final AppLanguage language;

  const AppStrings(this.language);

  String t(String key) =>
      _strings[language]?[key] ?? _strings[AppLanguage.ru]?[key] ?? key;

  String format(String key, Map<String, Object?> values) {
    var out = t(key);
    for (final entry in values.entries) {
      out = out.replaceAll('{${entry.key}}', '${entry.value}');
    }
    return out;
  }

  String meal(String key) => t('meal.$key');
  String nutrient(String key) => t('nutrient.$key');
  String unit(String key) => t('unit.$key');
  String addToMeal(String meal) => format('food.addToMeal', {'meal': meal});
  String addedCount(int count) => format('food.addedCount', {'count': count});
  String addedKcal(int kcal) => format('food.addedKcal', {'kcal': kcal});
  String addedName(String name) => format('food.addedName', {'name': name});
  String inMeal(int count, int kcal) =>
      format('food.inMeal', {'count': count, 'kcal': kcal});
  String selectedFoods(int count, int kcal) =>
      format('food.selectedFoods', {'count': count, 'kcal': kcal});
  String addCount(int count) => format('common.addCount', {'count': count});
  String doneCount(int count) => format('common.doneCount', {'count': count});
  String ageValue(int age) => format('profile.ageValue', {'age': age});
  String birthValue(DateTime d) => '${d.day.toString().padLeft(2, '0')}.'
      '${d.month.toString().padLeft(2, '0')}.${d.year}';

  String weekdayShort(int weekday) => _weekdays[language]![weekday - 1];
  String monthShort(int month) => _months[language]![month - 1];
  String monthName(int month) => _monthsFull[language]![month - 1];
  String dayMonth(DateTime date) => '${date.day} ${monthShort(date.month)}';
  String weekdayDayMonth(DateTime date) =>
      '${weekdayShort(date.weekday)}, ${dayMonth(date)}';

