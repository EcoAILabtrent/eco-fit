extension AppStringsContext on BuildContext {
  // Подписываемся ТОЛЬКО на смену языка (а не на любой notify стора). Раньше
  // здесь был watch<AppStore>(), из-за чего каждый виджет, читающий строку через
  // context.l10n, перестраивался на каждый тик шагомера/воды. select по языку
  // (enum со стабильным равенством) перестраивает их лишь при реальной смене языка.
  AppStrings get l10n =>
      AppStrings(select<AppStore, AppLanguage>((s) => s.language));
  AppStrings get l10nRead => AppStrings(read<AppStore>().language);
}
